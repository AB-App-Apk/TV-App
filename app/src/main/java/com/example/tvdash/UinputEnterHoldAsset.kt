package com.example.tvdash

import android.content.Context
import java.io.File
import java.io.FileOutputStream
import java.io.IOException
import java.security.MessageDigest

/**
 * Extracts the packaged ARMv7 Enter probe into app-private storage and verifies it before publishing it.
 *
 * This class deliberately does not chmod or execute the file. Root staging and process execution are a
 * separate phase, after the bytes have been validated and the caller has confirmed the supported device.
 */
internal object UinputEnterHoldAsset {
    private const val ASSET_BINARY = "uinput/armeabi-v7a/uinput_enter_hold_probe"
    private const val ASSET_MANIFEST = "uinput/armeabi-v7a/uinput_enter_hold_probe.sha256"
    private const val FILE_NAME = "uinput_enter_hold_probe"
    private const val MAX_BINARY_BYTES = 256 * 1024L

    /**
     * Returns a verified, non-executable app-private copy.
     *
     * The content-addressed destination avoids accidentally reusing an older executable after an APK update.
     * A temporary file is synced and hashed before its atomic rename makes it visible to other app code.
     */
    @Synchronized
    @Throws(IOException::class)
    fun prepare(context: Context): File {
        val appContext = context.applicationContext
        val expectedHash = appContext.assets.open(ASSET_MANIFEST).bufferedReader(Charsets.US_ASCII).use {
            parseUinputEnterHoldManifest(it.readText())
        }

        val directory = File(appContext.noBackupFilesDir, "uinput-enter-hold")
        if (!directory.isDirectory && !directory.mkdirs()) {
            throw IOException("Could not create private uinput directory: ${directory.absolutePath}")
        }

        val destination = File(directory, "${FILE_NAME}-$expectedHash")
        if (destination.exists()) {
            if (destination.isFile && sha256(destination) == expectedHash) {
                return destination
            }
            if (!destination.delete()) {
                throw IOException("Could not remove invalid cached uinput executable: ${destination.absolutePath}")
            }
        }

        val temporary = File.createTempFile("uinput-enter-hold-", ".tmp", directory)
        try {
            val digest = MessageDigest.getInstance("SHA-256")
            var totalBytes = 0L
            appContext.assets.open(ASSET_BINARY).use { input ->
                FileOutputStream(temporary).use { output ->
                    val buffer = ByteArray(8192)
                    while (true) {
                        val count = input.read(buffer)
                        if (count < 0) break
                        totalBytes += count
                        if (totalBytes > MAX_BINARY_BYTES) {
                            throw IOException("Packaged uinput executable exceeds size limit: $totalBytes bytes")
                        }
                        digest.update(buffer, 0, count)
                        output.write(buffer, 0, count)
                    }
                    output.fd.sync()
                }
            }

            val actualHash = digest.digest().joinToString("") { "%02x".format(it.toInt() and 0xff) }
            if (totalBytes == 0L || actualHash != expectedHash) {
                throw IOException(
                    "Packaged uinput executable checksum mismatch: expected=$expectedHash actual=$actualHash bytes=$totalBytes"
                )
            }

            if (!temporary.renameTo(destination)) {
                // Another process may have published the same content-addressed file first.
                if (destination.isFile && sha256(destination) == expectedHash) {
                    return destination
                }
                throw IOException("Could not atomically publish verified uinput executable: ${destination.absolutePath}")
            }

            return destination
        } finally {
            if (temporary.exists()) temporary.delete()
        }
    }

    private fun sha256(file: File): String {
        val digest = MessageDigest.getInstance("SHA-256")
        file.inputStream().buffered().use { input ->
            val buffer = ByteArray(8192)
            while (true) {
                val count = input.read(buffer)
                if (count < 0) break
                digest.update(buffer, 0, count)
            }
        }
        return digest.digest().joinToString("") { "%02x".format(it) }
    }
}

/** Strictly accepts the one-line sha256sum format generated by the packaging workflow. */
internal fun parseUinputEnterHoldManifest(text: String): String {
    val line = text.removeSuffix("\n").removeSuffix("\r")
    val match = Regex("^([0-9a-f]{64})  uinput_enter_hold_probe$").matchEntire(line)
        ?: throw IOException("Invalid uinput executable SHA-256 manifest")
    return match.groupValues[1]
}
